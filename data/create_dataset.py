def generate_dataset(output_path="data/language_dataset.csv"):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    rows = []
    
    for language, sentences in LANGUAGE_CORPUS.items():
        for sentence in sentences:
            clean_sentence = sentence.strip()
            if clean_sentence:
                rows.append({"text": clean_sentence, "language": language})
                
    with open(output_path, mode="w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["text", "language"])
        writer.writeheader()
        writer.writerows(rows)
        
    print(f"Generated {len(rows)} samples across {len(LANGUAGE_CORPUS)} languages into {output_path}")

if __name__ == "__main__":
    generate_dataset()
