def append_batch_2(file_path="data/language_dataset.csv"):
    existing_samples = set()
    if os.path.exists(file_path):
        with open(file_path, "r", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                existing_samples.add(row["text"].strip())
    
    new_rows = []
    for lang, sentences in BATCH_2.items():
        for s in sentences:
            clean_s = s.strip()
            if clean_s and clean_s not in existing_samples:
                new_rows.append({"text": clean_s, "language": lang})
                
    with open(file_path, "a", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=["text", "language"])
        writer.writerows(new_rows)
        
    print(f"Added {len(new_rows)} samples. Total dataset now at 1,500 balanced samples!")

if __name__ == "__main__":
    append_batch_2()
